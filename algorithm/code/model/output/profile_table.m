function T=profile_table(C,grid,state)
%PROFILE_TABLE Explicit names and units;no placeholder history or zero columns.
T=table(grid.centers*1e6,state.rhoLiquid,state.rhoMixture,state.u, ...
    state.p*1e-6,state.pressureElectric*1e-6,state.ptotal*1e-6,state.alpha, ...
    state.bubbleRadius*1e9,state.epsilon/C.epsilon0,state.Er*1e-9, ...
    state.massTransferRate,'VariableNames',{'r_um','rho_l','rho_m','u', ...
    'p_MPa','pE_MPa','ptotal_MPa','alpha','R_B_nm','epsilon_r','E_GV_m','mDot'});
end
